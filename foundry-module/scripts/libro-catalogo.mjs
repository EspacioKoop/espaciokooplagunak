// Catálogo de OBRAS del libro interactuable (#853, vertical 2): una ficha por
// obra, validada por el MISMO camino que las piezas del museo — no se
// reescribe la regla de licencia, se reusa `validarCatalogoPiezas` entera
// (#598), que a su vez descansa en `procedencia-catalogo.mjs`.
//
// POR QUÉ ENCAJA EN `catalogo-piezas.mjs` AUNQUE NO HAYA MALLA IMPORTADA. El
// campo `malla` de esa ficha es un ID que el CONSUMIDOR resuelve — para las
// estatuas es un nombre en `MALLAS_MUSEO` (una malla convertida de un STL, ver
// `tools/convertir-estatua.mjs`); aquí es un nombre que `libro-museo.mjs`
// resuelve a una SEMILLA procedural en vez de a un fichero. El validador no
// sabe ni le importa de dónde sale la geometría: solo comprueba que el ID
// declarado exista en el conjunto que se le pase, y eso es exactamente lo que
// hace `MALLAS_LIBRO` más abajo — el mismo papel que `MALLAS_MUSEO` cumple
// para las tres estatuas.
//
// `naturaleza: "obra-propia"`, Y NO "interpretacion". El validador solo admite
// los cinco valores de `NATURALEZAS` (`catalogo-piezas.mjs`) y hoy no hay un
// sexto que describa "procedural, inspirado en, sin reproducir nada". No es
// una aproximación forzada: la mancha que se pinta la GENERA este módulo
// (`libro-pagina.mjs`, regla dura de #526/#838 — nunca letra legible, nunca la
// imagen real), no es una digitalización de nada, así que "obra-propia" es
// literalmente lo que es. La obra clásica que inspira la cartela se cita como
// fuente NARRATIVA, no como procedencia del archivo — de ahí que
// `provenance.kind` sea "original" y no "cc": no se ha copiado ni un byte de
// ningún archivo de esa edición, así que no hay licencia de terceros que
// declarar. Si `catalogo-piezas.mjs` gana algún día una `naturaleza` para
// "inspirado en, sin reproducir", esta ficha es la primera candidata a migrar
// — no antes: inventar el valor aquí sería la misma norma que #598 ya prohíbe
// para saltarse la validación por comodidad.
//
// UNA obra y no un lote (disciplina de #590 aplicada aquí): la primera, para
// medir el precio de la cartela antes de escribir la segunda. El precio no es
// la geometría —ya está resuelta, procedural y gratis— sino decidir bien QUÉ
// se homenajea y decirlo sin adornar la verdad.
//
// Puro: datos y una sola llamada de validación al importar. Ni Foundry, ni
// DOM, ni red.

import { validarCatalogoPiezas } from "./catalogo-piezas.mjs";

/** El único ID de "malla" que declara este catálogo. `libro-museo.mjs` lo
 *  resuelve a geometría PROCEDURAL, nunca a un fichero — pero el validador
 *  solo necesita saber que el ID existe en algún registro, y este conjunto es
 *  ese registro, igual que `MALLAS_MUSEO` para las estatuas. */
export const MALLAS_LIBRO = Object.freeze(new Set(["grabados-clasicos"]));

export const ID_LIBRO_CLASICO = "grabados-clasicos";

export const CATALOGO_LIBROS = Object.freeze({
  formato: "espaciokoop-piezas",
  version: 1,
  piezas: Object.freeze([
    Object.freeze({
      id: ID_LIBRO_CLASICO,
      malla: ID_LIBRO_CLASICO,
      naturaleza: "obra-propia",
      nombre: Object.freeze({
        es: "Grabados de un clásico",
        en: "Engravings of a classic",
      }),
      cartela: Object.freeze({
        es: "Estas páginas no reproducen ningún archivo: la mancha que ves la"
          + " genera el propio módulo, página a página, sin una sola letra"
          + " legible — la misma regla de esta nave para cualquier superficie"
          + " que se mira de cerca. Su carácter de grabado rinde homenaje a los"
          + " aguafuertes que Gustave Doré hizo para La Divina Comedia (1861),"
          + " hoy de dominio público en todo el mundo; nada de ese archivo se"
          + " ha copiado aquí, y por eso esta ficha no lleva licencia de"
          + " terceros — es obra propia del módulo, de principio a fin.",
        en: "These pages reproduce no file: the mark you see is generated by"
          + " the module itself, page by page, with not a single legible"
          + " letter — the same house rule for any surface seen up close. Its"
          + " engraving character pays homage to the etchings Gustave Doré"
          + " made for the Divine Comedy (1861), today in the public domain"
          + " worldwide; nothing from that archive has been copied here, so"
          + " this entry carries no third-party licence — it is the module's"
          + " own work, start to finish.",
      }),
      provenance: Object.freeze({
        kind: "original",
        source: "Espaciokoop Lagunak — mancha tipográfica procedural (libro-pagina.mjs)",
        license: "GPL-2.0, igual que el resto del código del módulo",
      }),
    }),
  ]),
});

// Validado al importar, igual que `libro-pagina.mjs` valida su presupuesto:
// una ficha rota no debería llegar a montarse en la escena, debería tumbar la
// carga del módulo con un error que diga exactamente qué campo falla.
validarCatalogoPiezas(CATALOGO_LIBROS, { mallasDisponibles: MALLAS_LIBRO });
